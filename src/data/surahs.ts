// Helper to determine which volume a surah belongs to
export function getVolumeForSurah(surahNum: number): number {
  if (surahNum <= 2) return 1;
  if (surahNum <= 5) return 2;
  if (surahNum <= 9) return 3;
  if (surahNum <= 18) return 4;
  if (surahNum <= 33) return 5;
  if (surahNum <= 49) return 6;
  return 7;
}

