// Asynchronous fetcher with retry & fallback
export async function fetchSurahVerses(surahNumber: number): Promise<Ayah[]> {
  // If we already have sample verses for this surah, return them if offline,
  // but let's try fetching the full surah from the Al-Quran Cloud API.
  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 6000);

    const response = await fetch(
      `https://api.alquran.cloud/v1/surah/${surahNumber}/editions/quran-uthmani,ur.jalandhry,en.sahih`,
      { signal: controller.signal }
    );
    clearTimeout(timeoutId);

    if (response.ok) {
      const data = await response.json();
      if (data.status === 'OK' && data.data && data.data.length >= 3) {
        const arabicVerses = data.data[0].ayahs;
        const urduVerses = data.data[1].ayahs;
        const englishVerses = data.data[2].ayahs;

        const pad3 = (n: number) => n.toString().padStart(3, '0');
        const sPad = pad3(surahNumber);

        return arabicVerses.map((v: any, index: number) => {
          const aPad = pad3(v.numberInSurah);
          return {
            number: v.number,
            numberInSurah: v.numberInSurah,
            textArabic: v.text,
            textUrdu: urduVerses[index]?.text || '',
            textEnglish: englishVerses[index]?.text || '',
            juz: v.juz,
            audioUrl: `https://everyayah.com/data/Alafasy_128kbps/${sPad}${aPad}.mp3`
          };
        });
      }
    }
  } catch (err) {
    // Graceful fallback to bundled sample verses
    console.warn(`Could not fetch full surah ${surahNumber} from network, checking local cache:`, err);
  }

  if (SAMPLE_AYAHS[surahNumber]) {
    return SAMPLE_AYAHS[surahNumber];
  }

  // If not bundled, construct a helpful placeholder set indicating internet connectivity or surah metadata
  return [
    {
      number: 1,
      numberInSurah: 1,
      textArabic: 'بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ',
      textUrdu: 'شروع اللہ کے نام سے جو بڑا مہربان نہایت رحم والا ہے',
      textEnglish: 'In the name of Allah, the Entirely Merciful, the Especially Merciful.',
      juz: 1,
      audioUrl: `https://everyayah.com/data/Alafasy_128kbps/${surahNumber.toString().padStart(3, '0')}001.mp3`
    }
  ];
}
